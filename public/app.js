function computeDocChecklist(catKey, jenisKerjasama, isIndo) {
  const base = (DOC_BASE_TRACKS[catKey] || DOC_BASE_TRACKS.personal)[isIndo ? 'id' : 'en'];
  if (jenisKerjasama === 'Partnership') {
    return isIndo
      ? ['KTP Entitas Usaha (Beneficial Owner)', 'NPWP Entitas Usaha (Beneficial Owner)']
      : ['Business Entity ID Card / KTP (Beneficial Owner)', 'Business Entity Tax ID / NPWP (Beneficial Owner)'];
  }
  if (jenisKerjasama === 'Referral Premium') {
    const extra = isIndo
      ? ['PKS Outlet', 'KTP Outlet', 'Form Outlet']
      : ['Outlet Cooperation Agreement (PKS)', 'Outlet ID Card (KTP)', 'Outlet Registration Form'];
    return base.concat(extra);
  }
  return base;
}

