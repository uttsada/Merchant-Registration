async function callGemini(prompt, systemInstruction = null) {
  const apiKey = "";
  const apiUrl = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${apiKey}`;
  const payload = { contents: [{ parts: [{ text: prompt }] }] };
  if (systemInstruction) payload.systemInstruction = { parts: [{ text: systemInstruction }] };
  try {
    const response = await fetch(apiUrl, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(payload) });
    if (!response.ok) throw new Error(`HTTP status ${response.status}`);
    const result = await response.json();
    return result.candidates?.[0]?.content?.parts?.[0]?.text || "Jawaban sistem.";
  } catch (err) {
    if (prompt.toLowerCase().includes('nib') || prompt.toLowerCase().includes('kemenkumham')) {
      return "**NIB (Nomor Induk Berusaha)** adalah identitas berusaha resmi OSS/BKPM. **SK Kemenkumham** adalah bukti legalitas pengesahan badan hukum perseroan dari Kementerian Hukum dan HAM.";
    }
    return "Lumina Pay Onboarding Copilot siap membantu memahami regulasi KYB Indonesia.";
  }
}

