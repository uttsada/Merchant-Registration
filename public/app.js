function wzMoney(v) {
  if (v === '' || v == null) return '';
  if (typeof v === 'string' && /[^\d.,\s]/.test(v)) return v;
  const n = Number(String(v).replace(/[^\d]/g, ''));
  return isNaN(n) ? String(v) : 'Rp ' + n.toLocaleString('id-ID');
}

function wzNum(v) {
  const n = Number(String(v).replace(/[^\d]/g, ''));
  return (v === '' || v == null || isNaN(n)) ? String(v) : n.toLocaleString('id-ID');
}

