function renderPhaseRibbon() {
  const lang = state.lang;
  const curIdx = ORDER.indexOf(state.curStep);
  const nav = NAV(lang);
  const el = document.getElementById('phase-ribbon');
  if (!el) return;
  let parts = ['<div class="flex items-stretch gap-2 sm:gap-3">'];
  let activeSec = null;
  for (let si = 0; si < nav.length; si++) {
    const sec = nav[si];
    let done = 0;
    let isActivePhase = false;
    for (let k = 0; k < sec.items.length; k++) {
      if (ORDER.indexOf(sec.items[k].id) < curIdx) done++;
      if (sec.items[k].id === state.curStep) isActivePhase = true;
    }
    if (isActivePhase) activeSec = sec;
    const phaseDone = (done === sec.items.length);
    const chipCls = isActivePhase ? 'border-2 border-[#1E3A8A] bg-slate-50' : phaseDone ? 'border-2 border-emerald-200 bg-emerald-50/40' : 'border-2 border-slate-200 bg-white';
    const badgeCls = isActivePhase ? 'bg-[#1E3A8A] text-white' : phaseDone ? 'bg-[#059669] text-white' : 'border border-slate-300 text-slate-500';
    const titleCls = isActivePhase ? 'text-[#1E3A8A]' : phaseDone ? 'text-emerald-800' : 'text-slate-500';
    if (si > 0) parts.push('<div class="flex items-center text-slate-300">→</div>');
    parts.push(
      `<button onclick="openStep('${sec.items[0].id}')" class="flex-1 text-left rounded-xl p-3 transition ${chipCls}">` +
      `<div class="flex items-center justify-between"><span class="w-6 h-6 rounded-full text-[11px] font-bold flex items-center justify-center ${badgeCls}">${phaseDone ? '✓' : sec.n}</span><span class="text-[10px] font-bold px-2 py-0.5 rounded-full bg-slate-100 text-slate-600">${done}/${sec.items.length}</span></div>` +
      `<p class="text-[12px] font-bold mt-2 ${titleCls}">${sec.title}</p>` +
      `</button>`
    );
  }
  parts.push('</div>');
  el.innerHTML = parts.join('');
}

